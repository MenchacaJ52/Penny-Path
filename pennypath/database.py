"""
PostgreSQL persistence for all three front ends (web, desktop, CLI).

Connection settings come from the DATABASE_URL environment variable, e.g.
    postgresql://pennypath:<password>@localhost:5432/pennypath
(see the "Database setup" section of README.md). Connections come from a thread-safe pool, so
the Flask server can handle concurrent requests. The pool opens lazily on first
use; call `ensure_ready()` at startup to fail fast with a helpful message.

Money columns are NUMERIC (exact cents) but are returned to Python as float,
since the rest of the app does float arithmetic.
"""
import atexit
import os
import threading

import psycopg
from psycopg import sql
from psycopg.conninfo import conninfo_to_dict
from psycopg.types.numeric import FloatLoader
from psycopg_pool import ConnectionPool

SETUP_HELP = """PennyPath needs a PostgreSQL database.
  1. Create the database (once):  psql -U postgres -f scripts/setup_postgres.sql
  2. Set DATABASE_URL, e.g.:      postgresql://pennypath:<password>@localhost:5432/pennypath
See the "Database setup" section of README.md for details."""

SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      TEXT        NOT NULL UNIQUE,
    password_hash TEXT        NOT NULL,
    onboarded     BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS accounts (
    id      TEXT          NOT NULL,                -- 'checking' | 'savings' | 'wage'
    user_id INTEGER       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    balance NUMERIC(14,2) NOT NULL DEFAULT 0,
    PRIMARY KEY (id, user_id)
);
CREATE TABLE IF NOT EXISTS wages (
    user_id     INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    weekly_wage DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (weekly_wage >= 0)  -- a rate, not a ledger amount
);
CREATE TABLE IF NOT EXISTS expenses (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    category    TEXT          NOT NULL CHECK (category IN ('needs', 'wants')),
    subcategory TEXT          NOT NULL DEFAULT 'other',
    name        TEXT          NOT NULL,
    amount      NUMERIC(14,2) NOT NULL CHECK (amount >= 0),
    frequency   TEXT          NOT NULL
);
CREATE INDEX IF NOT EXISTS expenses_user_id_idx ON expenses (user_id);
CREATE TABLE IF NOT EXISTS budget (
    user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    amount  NUMERIC(14,2) NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS chat_feedback (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INTEGER     NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    question   TEXT        NOT NULL,
    response   TEXT        NOT NULL,
    reward     SMALLINT    NOT NULL CHECK (reward IN (-1, 1)),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS debt (                  -- total debt shown on the dashboard
    user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    amount  NUMERIC(14,2) NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS debts (                 -- itemized debts for the Debt Plan
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name        TEXT          NOT NULL,
    balance     NUMERIC(14,2) NOT NULL CHECK (balance > 0),
    apr         NUMERIC(6,3)  NOT NULL CHECK (apr >= 0),
    min_payment NUMERIC(14,2) NOT NULL CHECK (min_payment > 0)
);
CREATE INDEX IF NOT EXISTS debts_user_id_idx ON debts (user_id);
CREATE TABLE IF NOT EXISTS profiles (
    user_id        INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    full_name      TEXT        NOT NULL DEFAULT '',
    age            SMALLINT,
    email          TEXT        NOT NULL DEFAULT '',
    occupation     TEXT        NOT NULL DEFAULT '',
    state          TEXT        NOT NULL DEFAULT '',
    household_size SMALLINT,
    primary_goal   TEXT        NOT NULL DEFAULT '',
    risk_tolerance TEXT        NOT NULL DEFAULT '',
    pay_frequency  TEXT        NOT NULL DEFAULT 'weekly',
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);
"""


class DatabaseNotConfigured(RuntimeError):
    """DATABASE_URL is missing or the server can't be reached."""


def describe(url: str) -> str:
    """Connection target for messages, without the password."""
    try:
        p = conninfo_to_dict(url)
    except psycopg.ProgrammingError:
        return "(unparseable DATABASE_URL)"
    return f"{p.get('user', '?')}@{p.get('host', 'localhost')}:{p.get('port', 5432)}/{p.get('dbname', '?')}"


class Database:
    def __init__(self, url: str | None = None, schema: str | None = None,
                 max_size: int = 10):
        """`schema` sets the search_path — used by tests to isolate each test."""
        self.url = url or os.environ.get("DATABASE_URL")
        self._kwargs = {"options": f"-c search_path={schema}"} if schema else {}
        self._max_size = max_size
        self._pool: ConnectionPool | None = None
        self._lock = threading.Lock()

    # ── Connection management ─────────────────────────────────────────────
    @staticmethod
    def _configure(conn: psycopg.Connection):
        conn.adapters.register_loader("numeric", FloatLoader)

    def ensure_ready(self):
        """Connect, create the pool, and create tables. Safe to call repeatedly."""
        if self._pool is not None:
            return
        with self._lock:
            if self._pool is not None:
                return
            if not self.url:
                raise DatabaseNotConfigured("DATABASE_URL is not set.\n\n" + SETUP_HELP)
            try:   # one direct connection first: gives a clear error (bad password, no server…)
                with psycopg.connect(self.url, connect_timeout=5, **self._kwargs) as conn:
                    conn.execute(SCHEMA)
            except psycopg.OperationalError as e:
                raise DatabaseNotConfigured(
                    f"Could not connect to PostgreSQL at {describe(self.url)}:\n"
                    f"  {str(e).strip()}\n\n{SETUP_HELP}") from None
            pool = ConnectionPool(self.url, min_size=1, max_size=self._max_size,
                                  kwargs=self._kwargs, configure=self._configure, open=False)
            pool.open(wait=True, timeout=10)
            self._pool = pool
            # Close the pool's worker threads cleanly even if the app never calls close()
            # (e.g. the desktop window is closed); otherwise Python errors at shutdown.
            atexit.register(self.close)

    def _run(self, query, params=(), fetch: str | None = None):
        """Execute one statement in its own transaction (committed on success).
        fetch: None → rowcount, 'one' → first row, 'all' → all rows."""
        self.ensure_ready()
        with self._pool.connection() as conn:
            cur = conn.execute(query, params)
            if fetch == "one":
                return cur.fetchone()
            if fetch == "all":
                return cur.fetchall()
            return cur.rowcount

    def close(self):
        if self._pool is not None:
            self._pool.close()
            self._pool = None

    # ── Users ─────────────────────────────────────────────────────────────
    def create_user(self, username: str, password_hash: str) -> bool:
        try:
            self._run("INSERT INTO users (username, password_hash) VALUES (%s, %s)",
                      (username, password_hash))
            return True
        except psycopg.errors.UniqueViolation:
            return False  # username taken

    def get_user(self, username: str):
        """Returns (id, username, password_hash, onboarded) or None."""
        return self._run(
            "SELECT id, username, password_hash, onboarded FROM users WHERE username = %s",
            (username,), fetch="one")

    def get_password_hash(self, user_id: int) -> str | None:
        row = self._run("SELECT password_hash FROM users WHERE id = %s", (user_id,), fetch="one")
        return row[0] if row else None

    def update_password(self, user_id: int, password_hash: str):
        self._run("UPDATE users SET password_hash = %s WHERE id = %s", (password_hash, user_id))

    def mark_onboarded(self, user_id: int):
        self._run("UPDATE users SET onboarded = TRUE WHERE id = %s", (user_id,))

    # ── Accounts ──────────────────────────────────────────────────────────
    def save_account(self, account_id: str, balance: float, user_id: int):
        self._run(
            "INSERT INTO accounts (id, user_id, balance) VALUES (%s, %s, %s) "
            "ON CONFLICT (id, user_id) DO UPDATE SET balance = excluded.balance",
            (account_id, user_id, balance))

    def load_account(self, account_id: str, user_id: int) -> float:
        row = self._run("SELECT balance FROM accounts WHERE id = %s AND user_id = %s",
                        (account_id, user_id), fetch="one")
        return row[0] if row else 0.0

    # ── Wages ─────────────────────────────────────────────────────────────
    def save_wage(self, weekly_wage: float, user_id: int):
        self._run(
            "INSERT INTO wages (user_id, weekly_wage) VALUES (%s, %s) "
            "ON CONFLICT (user_id) DO UPDATE SET weekly_wage = excluded.weekly_wage",
            (user_id, weekly_wage))

    def load_wage(self, user_id: int) -> float:
        row = self._run("SELECT weekly_wage FROM wages WHERE user_id = %s", (user_id,),
                        fetch="one")
        return row[0] if row else 0.0

    # ── Expenses ──────────────────────────────────────────────────────────
    def save_expense(self, category: str, subcategory: str, name: str, amount: float,
                     frequency: str, user_id: int) -> int:
        """Insert an expense and return its new id."""
        return self._run(
            "INSERT INTO expenses (user_id, category, subcategory, name, amount, frequency) "
            "VALUES (%s, %s, %s, %s, %s, %s) RETURNING id",
            (user_id, category, subcategory, name, amount, frequency), fetch="one")[0]

    def load_expenses(self, user_id: int) -> list:
        """Rows of (id, category, subcategory, name, amount, frequency), oldest first."""
        return self._run(
            "SELECT id, category, subcategory, name, amount, frequency "
            "FROM expenses WHERE user_id = %s ORDER BY id", (user_id,), fetch="all")

    def update_expense(self, expense_id: int, user_id: int, category: str, subcategory: str,
                       name: str, amount: float, frequency: str) -> bool:
        return self._run(
            "UPDATE expenses SET category = %s, subcategory = %s, name = %s, amount = %s, "
            "frequency = %s WHERE id = %s AND user_id = %s",
            (category, subcategory, name, amount, frequency, expense_id, user_id)) > 0

    def delete_expense(self, expense_id: int, user_id: int) -> bool:
        return self._run("DELETE FROM expenses WHERE id = %s AND user_id = %s",
                         (expense_id, user_id)) > 0

    def clear_expenses(self, user_id: int):
        self._run("DELETE FROM expenses WHERE user_id = %s", (user_id,))

    # ── Budget ────────────────────────────────────────────────────────────
    def save_budget(self, amount: float, user_id: int):
        self._run(
            "INSERT INTO budget (user_id, amount) VALUES (%s, %s) "
            "ON CONFLICT (user_id) DO UPDATE SET amount = excluded.amount",
            (user_id, amount))

    def load_budget(self, user_id: int) -> float:
        row = self._run("SELECT amount FROM budget WHERE user_id = %s", (user_id,), fetch="one")
        return row[0] if row else 0.0

    # ── Session helpers ───────────────────────────────────────────────────
    def save_session(self, savings_bal, checking_bal, wage, budget_amt, user_id: int,
                     wage_account_bal: float | None = None):
        self.save_account("savings",  savings_bal,  user_id)
        self.save_account("checking", checking_bal, user_id)
        self.save_wage(wage, user_id)
        if budget_amt is not None:
            self.save_budget(budget_amt, user_id)
        if wage_account_bal is not None:
            self.save_account("wage", wage_account_bal, user_id)

    def load_session(self, user_id: int):
        return {
            "savings":  self.load_account("savings",  user_id),
            "checking": self.load_account("checking", user_id),
            "wage_account": self.load_account("wage", user_id),
            "wage":     self.load_wage(user_id),
            "budget":   self.load_budget(user_id),
            "expenses": self.load_expenses(user_id),
            "debt":     self.load_debt(user_id),
        }

    # ── Chat feedback ─────────────────────────────────────────────────────
    def save_feedback(self, user_id: int, question: str, response: str, reward: int):
        """Store a thumbs-up (+1) or thumbs-down (-1) rating for a Q&A pair."""
        self._run("INSERT INTO chat_feedback (user_id, question, response, reward) "
                  "VALUES (%s, %s, %s, %s)", (user_id, question, response, reward))

    def get_positive_feedback(self, user_id: int, limit: int = 50) -> list:
        """Return (question, response) pairs the user rated positively, newest first."""
        return self._run(
            "SELECT question, response FROM chat_feedback WHERE user_id = %s AND reward > 0 "
            "ORDER BY created_at DESC LIMIT %s", (user_id, limit), fetch="all")

    # ── Debt total ────────────────────────────────────────────────────────
    def save_debt(self, amount: float, user_id: int):
        self._run(
            "INSERT INTO debt (user_id, amount) VALUES (%s, %s) "
            "ON CONFLICT (user_id) DO UPDATE SET amount = excluded.amount",
            (user_id, amount))

    def load_debt(self, user_id: int) -> float:
        row = self._run("SELECT amount FROM debt WHERE user_id = %s", (user_id,), fetch="one")
        return row[0] if row else 0.0

    # ── Itemized debts (Debt Plan) ────────────────────────────────────────
    # When a user has itemized debts, their total is kept in sync with the
    # single `debt` figure shown on the dashboard.
    def load_debts(self, user_id: int) -> list[dict]:
        rows = self._run(
            "SELECT id, name, balance, apr, min_payment FROM debts WHERE user_id = %s ORDER BY id",
            (user_id,), fetch="all")
        return [dict(id=r[0], name=r[1], balance=r[2], apr=r[3], min_payment=r[4]) for r in rows]

    def _sync_debt_total(self, user_id: int):
        self._run(
            "INSERT INTO debt (user_id, amount) "
            "SELECT %s, COALESCE(SUM(balance), 0) FROM debts WHERE user_id = %s "
            "ON CONFLICT (user_id) DO UPDATE SET amount = excluded.amount",
            (user_id, user_id))

    def add_debt(self, user_id: int, name: str, balance: float, apr: float,
                 min_payment: float) -> int:
        new_id = self._run(
            "INSERT INTO debts (user_id, name, balance, apr, min_payment) "
            "VALUES (%s, %s, %s, %s, %s) RETURNING id",
            (user_id, name, balance, apr, min_payment), fetch="one")[0]
        self._sync_debt_total(user_id)
        return new_id

    def delete_debt(self, debt_id: int, user_id: int) -> bool:
        deleted = self._run("DELETE FROM debts WHERE id = %s AND user_id = %s",
                            (debt_id, user_id)) > 0
        self._sync_debt_total(user_id)
        return deleted

    # ── Profile ───────────────────────────────────────────────────────────
    PROFILE_FIELDS = ("full_name", "age", "email", "occupation", "state",
                      "household_size", "primary_goal", "risk_tolerance", "pay_frequency")

    def load_profile(self, user_id: int) -> dict:
        row = self._run(
            sql.SQL("SELECT {} FROM profiles WHERE user_id = %s").format(
                sql.SQL(", ").join(map(sql.Identifier, self.PROFILE_FIELDS))),
            (user_id,), fetch="one")
        if row is None:
            return {f: None if f in ("age", "household_size") else "" for f in self.PROFILE_FIELDS} \
                   | {"pay_frequency": "weekly"}
        return dict(zip(self.PROFILE_FIELDS, row))

    def save_profile(self, user_id: int, fields: dict):
        """Upsert any subset of PROFILE_FIELDS."""
        fields = {k: v for k, v in fields.items() if k in self.PROFILE_FIELDS}
        if not fields:
            return
        cols = [sql.Identifier(k) for k in fields]
        self._run(
            sql.SQL("INSERT INTO profiles (user_id, {cols}) VALUES (%s, {marks}) "
                    "ON CONFLICT (user_id) DO UPDATE SET {updates}, updated_at = now()").format(
                cols=sql.SQL(", ").join(cols),
                marks=sql.SQL(", ").join(sql.Placeholder() * len(fields)),
                updates=sql.SQL(", ").join(sql.SQL("{c} = excluded.{c}").format(c=c) for c in cols)),
            (user_id, *fields.values()))
